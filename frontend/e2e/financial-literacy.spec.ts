import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { resolve } from 'node:path'
import { loginAs } from './helpers.ts'

for (const theme of ['light', 'dark'] as const) for (const device of ['mobile', 'desktop'] as const) {
  test(`money and explanations ${theme} ${device}`, async ({page}, testInfo) => {
    test.setTimeout(90000)
    await page.emulateMedia({colorScheme: theme, reducedMotion: 'reduce'})
    await loginAs(page, `literacy-${theme}-${device}-${testInfo.retry}@example.test`)
    await page.setViewportSize(device === 'mobile' ? {width: 375, height: 812} : {width: 1280, height: 900})
    await page.goto('/')
    await page.getByLabel('Stock files (.csv, .xlsx, .pdf)').setInputFiles(resolve('../test_data/epic_share_summary.csv'))
    await page.getByRole('button', {name: 'Read my files', exact: true}).click()
    await page.getByRole('button', {name: 'Review and save'}).click()
    await page.getByRole('button', {name: /^Save \d+ changes/}).click()
    const tour = page.getByRole('region', {name: 'Your position tour'})
    await expect(tour).toBeVisible()
    await tour.getByRole('button', {name: 'Show me around'}).click()
    await expect(tour).toContainText('1 of 5')
    await tour.getByRole('button', {name: 'Next: Your loans'}).click()
    await expect(tour).toContainText('2 of 5')
    await tour.getByRole('button', {name: 'Dismiss tour'}).click()
    await expect(tour).toHaveCount(0)
    const basis = page.locator('[data-equity-card="basis"]').first()
    await basis.getByText('Cost basis · explain', {exact: true}).click()
    await expect(basis).toContainText('On this card:')
    expect((await new AxeBuilder({page}).analyze()).violations.filter(v => v.impact === 'critical' || v.impact === 'serious')).toEqual([])
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({path: `../screenshots/teaching-position-${theme}-${device}.png`, fullPage: true, style: '[aria-label="Mobile navigation"]{visibility:hidden!important}'})
    await page.reload()
    await expect(tour).toHaveCount(0)
    await page.goto('/retirement')
    const brokerage = page.getByLabel(/^Taxable brokerage at retirement/)
    await brokerage.fill('400000')
    await brokerage.blur()
    await expect(brokerage).toHaveValue('400000')
    await expect(brokerage.locator('..')).toContainText('= $400,000')
    const spending = page.getByLabel(/^Default spend/)
    await spending.fill('140000')
    await spending.blur()
    await expect(spending.locator('..')).toContainText('= $140,000 per year')
    await expect.poll(async () => (await (await page.request.get('/api/retirement/params')).json()).params?.taxableAdditional).toBe(0.4)
    await expect.poll(async () => (await (await page.request.get('/api/retirement/params')).json()).params?.defaultSpend).toBe(140)
    await brokerage.fill('1000000001')
    await brokerage.blur()
    await expect(brokerage).toHaveAttribute('aria-invalid', 'true')
    await expect(brokerage.locator('..')).toContainText('Enter a dollar amount')
    await brokerage.fill('400000')
    await brokerage.blur()
    await expect(brokerage).toHaveValue('400000')
    await expect(brokerage).toHaveAttribute('aria-invalid', 'false')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect((await new AxeBuilder({page}).analyze()).violations.filter(v => v.impact === 'critical' || v.impact === 'serious')).toEqual([])
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({path: `../screenshots/teaching-money-${theme}-${device}.png`, fullPage: true, style: '[aria-label="Mobile navigation"]{visibility:hidden!important}'})
    await page.goto('/settings#tax')
    const settings = page.locator('#tax')
    await settings.getByRole('button', {name: 'Edit', exact: true}).click()
    await settings.getByLabel('Federal income rate (%)', {exact: true}).fill('30')
    await settings.getByRole('button', {name: 'Save', exact: true}).click()
    await expect(settings.getByRole('button', {name: 'Confirm and save assumptions'})).toBeVisible()
    expect((await (await page.request.get('/api/tax-settings')).json()).federal_income_rate).not.toBe(0.30)
    await settings.getByRole('button', {name: 'Confirm and save assumptions'}).click()
    await expect(settings.getByRole('button', {name: 'Edit', exact: true})).toBeVisible()
    expect((await new AxeBuilder({page}).include('#tax').analyze()).violations.filter(v => v.impact === 'critical' || v.impact === 'serious')).toEqual([])
    await settings.screenshot({path: `../screenshots/teaching-settings-${theme}-${device}.png`})
  })
}
