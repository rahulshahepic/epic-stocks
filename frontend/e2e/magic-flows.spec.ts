import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { resolve } from 'node:path'
import { loginAs } from './helpers.ts'

for (const theme of ['light', 'dark'] as const) for (const device of ['mobile', 'desktop'] as const) {
  test(`position to retirement and price update ${theme} ${device}`, async ({page}, testInfo) => {
    test.setTimeout(90000)
    await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
    await loginAs(page, `magic-${theme}-${device}-${testInfo.retry}@example.test`)
    await page.setViewportSize(device === 'mobile' ? {width: 375, height: 812} : {width: 1280, height: 900})
    await page.goto('/')
    await page.getByLabel('Stock files (.csv, .xlsx, .pdf)').setInputFiles([
      resolve('../test_data/epic_loan_statement.pdf'), resolve('../test_data/epic_share_summary.csv'),
    ])
    await expect(page.getByRole('status').filter({hasText: 'Got your stock workbook'})).toContainText('Got your loan statement')
    await page.getByRole('button', {name: 'Read my files', exact: true}).click()
    await page.getByLabel('Current share price').fill('20')
    await page.getByRole('button', {name: 'Use this price', exact: true}).click()
    await page.getByRole('button', {name: 'Review and save'}).click()
    await page.getByRole('button', {name: /^Save \d+ changes/}).click()
    await expect(page.getByText('Your import is saved. Here’s your position.')).toBeVisible()
    await expect(page.getByText(/^You hold .* vested shares/)).toBeVisible()
    await expect(page.getByText(/^If you left today/)).toBeVisible()
    await expect(page.getByText('More charts · earnings, prices, tax and loans').locator('..')).not.toHaveAttribute('open')
    expect((await new AxeBuilder({page}).analyze()).violations.filter(v => v.impact === 'critical' || v.impact === 'serious')).toEqual([])
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({path: `../screenshots/magic-position-${theme}-${device}.png`, fullPage: true, style: '[aria-label="Mobile navigation"]{visibility:hidden!important}'})
    await page.request.patch('/api/me/profile', {data: {date_of_birth: '1980-01-01'}})
    await page.request.put('/api/retirement/params', {data: {params: {retirementDate: '2032-01-01', paths: 1000, seed: 1729, defaultSpend: 180, minSpend: 190}}})
    await page.getByRole('link', {name: 'Will it fund retirement? →'}).click()
    // These setup-only API writes bypass the browser's profile cache.
    await page.reload()
    await expect(page.getByText(/Through age 95/)).toBeVisible({timeout: 30000})
    await expect(page.getByRole('button', {name: 'Edit plan assumptions', exact: true})).toBeVisible()
    await expect(page.getByLabel(/^Default spend/)).toBeHidden()
    await page.getByRole('button', {name: 'Edit plan assumptions', exact: true}).click()
    await expect(page.getByRole('region', {name: 'Retirement plan inputs'})).toBeFocused()
    await page.getByRole('tab', {name: /^Spending/}).click()
    await expect(page.getByText(/spending floor \$180K\/year \(capped/)).toBeVisible()
    await page.getByRole('button', {name: 'Back to results', exact: true}).click()
    await expect(page.getByRole('region', {name: 'Retirement results'})).toBeFocused()
    await page.getByRole('button', {name: 'Edit plan assumptions', exact: true}).click()
    await expect(page.getByLabel(/^Default spend/)).toBeVisible()
    await page.getByRole('button', {name: 'Back to results', exact: true}).click()
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({path: `../screenshots/magic-retirement-${theme}-${device}.png`, fullPage: true, style: '[aria-label="Mobile navigation"]{visibility:hidden!important}'})
    await page.goto('/prices')
    const year = new Date().getFullYear()
    const current = (await (await page.request.get('/api/prices')).json()).find((p: {effective_date: string}) => p.effective_date === `${year}-01-01`)
    await page.request.put(`/api/prices/${current.id}`, {data: {announced_date: `${year}-01-01`, version: current.version}})
    await page.getByLabel('Announced price', {exact: true}).fill('42')
    await page.getByRole('button', {name: 'See what changes', exact: true}).click()
    await expect(page.getByText('Confirmed price: $42.00 per share, applicable ' + `${year}-01-01.`)).toBeVisible()
    await page.getByRole('button', {name: 'Save confirmed price', exact: true}).click()
    await expect(page.getByRole('heading', {name: 'Your position, updated'})).toBeVisible()
    await expect(page.getByText(/^If you left today/)).toBeVisible()
    const after = (await (await page.request.get('/api/prices')).json()).find((p: {id: number}) => p.id === current.id)
    expect(after.price).toBe(42)
    expect(after.announced_date).toBe(`${year}-01-01`)
    expect(after.is_estimate).toBe(false)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({path: `../screenshots/magic-price-${theme}-${device}.png`, fullPage: true, style: '[aria-label="Mobile navigation"]{visibility:hidden!important}'})
  })
}

