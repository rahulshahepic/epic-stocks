import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { loginAs } from './helpers.ts'

test('mobile settings categories open one at a time and support their primary actions', async ({ page }) => {
  await loginAs(page, `settings-categories-${test.info().retry}@example.test`)
  await page.route('**/api/config', async route => {
    const response = await route.fetch()
    await route.fulfill({ response, json: { ...await response.json(), email_notifications_available: true } })
  })
  await page.goto('/settings')
  const categories = page.getByRole('navigation', { name: 'Settings categories' })
  await expect(categories.getByRole('link')).toHaveCount(6)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])

  await categories.getByRole('link', { name: /^AI Connections/ }).click()
  await expect(categories).toBeHidden()
  await expect(page.getByText('Nothing connected yet.')).toBeVisible()
  await page.getByRole('link', { name: 'Connect an assistant' }).click()
  await expect(page.getByRole('heading', { name: 'Connect your AI' })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'AI Connections' })).toBeVisible()
  await page.getByRole('link', { name: 'Back to Settings' }).click()

  await categories.getByRole('link', { name: /^Notifications/ }).click()
  const email = page.getByText('Email notifications', { exact: true }).locator('../..')
  await email.getByRole('button', { name: 'Enable', exact: true }).click()
  await expect(email.getByRole('button', { name: 'Disable', exact: true })).toBeVisible()
  await page.reload()
  await expect(email.getByRole('button', { name: 'Disable', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Back to Settings' }).click()

  await categories.getByRole('link', { name: /^Appearance/ }).click()
  await page.getByRole('button', { name: 'Dark theme' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Dark theme' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('link', { name: 'Back to Settings' }).click()

  await categories.getByRole('link', { name: /^Sharing/ }).click()
  const invitee = 'settings-invited-person@example.com'
  await page.getByRole('textbox', { name: 'Email address to invite' }).fill(invitee)
  await page.getByRole('button', { name: 'Invite', exact: true }).click()
  await expect(page.getByText(invitee, { exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Invitation code' })).toBeVisible()
  await page.getByRole('link', { name: 'Back to Settings' }).click()

  await categories.getByRole('link', { name: /^Account/ }).click()
  await page.getByRole('button', { name: 'Delete Account', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Yes, delete my account' })).toBeVisible()
  await page.getByRole('link', { name: 'Back to Settings' }).click()
  await categories.getByRole('link', { name: /^Account/ }).click()
  await expect(page.getByRole('button', { name: 'Yes, delete my account' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Sign Out Everywhere' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
})

test('desktop loan deep link edits only loan assumptions and keeps settings navigation visible', async ({ page }) => {
  await loginAs(page, `settings-loans-${test.info().retry}@example.test`)
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/settings#loans')
  const before = await (await page.request.get('/api/tax-settings')).json()
  const categories = page.getByRole('navigation', { name: 'Settings categories' })
  const assumptions = page.getByRole('navigation', { name: 'Stock, tax and loan settings' })
  await expect(categories.getByRole('link', { name: /^Stock, Tax/ })).toHaveAttribute('aria-current', 'location')
  await expect(assumptions.getByRole('link', { name: 'Loans' })).toHaveAttribute('aria-current', 'location')
  await expect(page.getByRole('heading', { name: 'Taxes' })).toHaveCount(0)
  await page.getByRole('link', { name: 'Skip to main content' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('main')).toBeFocused()
  await expect(page).toHaveURL(/\/settings#loans$/)
  await expect(page.getByRole('heading', { name: 'Loan assumptions', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Future interest-loan rate (%)').fill('4.25')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm and save assumptions' }).click()
  await expect(page.getByText('4.25%', { exact: true })).toBeVisible()
  const after = await (await page.request.get('/api/tax-settings')).json()
  expect(after.projected_loan_rate).toBeCloseTo(0.0425)
  expect(after.federal_income_rate).toEqual(before.federal_income_rate)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])

  await assumptions.getByRole('link', { name: 'Stock down payment' }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByRole('checkbox', { name: /^Prefer stock for down payment/ }).check()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Yes — auto-calculate DP shares')).toBeVisible()
  const latest = await (await page.request.get('/api/tax-settings')).json()
  expect(latest.prefer_stock_dp).toBe(true)
  expect(latest.projected_loan_rate).toEqual(after.projected_loan_rate)

  await assumptions.getByRole('link', { name: 'Taxes' }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByRole('button', { name: 'Save', exact: true }).scrollIntoViewIfNeeded()
  await expect(categories.getByRole('link', { name: /^AI Connections/ })).toBeInViewport()
})

test('returning from Appearance restores the category link and its scroll position', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 460 })
  await loginAs(page, 'settings-scroll-restore@example.test')
  await page.goto('/settings')
  const appearance = page.getByRole('link', { name: /^Appearance/ })
  await expect(appearance).toBeVisible()
  const entryScroll = await page.evaluate(() => { window.scrollTo(0, 120); return window.scrollY })
  await expect(appearance).toBeInViewport()
  expect(entryScroll).toBeGreaterThan(0)
  await appearance.click()
  await expect(page.getByRole('button', { name: 'Dark theme' })).toBeVisible()
  await page.getByRole('link', { name: 'Back to Settings' }).click()
  await expect(appearance).toBeFocused()
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(entryScroll)
  await appearance.click()
  await page.goBack()
  await expect(appearance).toBeInViewport()
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(entryScroll)
})
