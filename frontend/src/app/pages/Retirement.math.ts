// Migrate a saved params blob from the legacy schema (single `additional`
// number + `refillTaxDrag`) into the new bucket model. Treats a legacy
// `additional` value as taxable with **zero basis** (fully appreciated) —
// the conservative assumption for non-Epic wealth that the user hadn't
// broken down. They can override basis explicitly in the advanced view.
// `refillTaxDrag` is dropped (replaced by the bracket-based tax engine).
export function migrateLoadedParams(saved: Record<string, unknown>): Partial<SimParams> {
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  const { additional, refillTaxDrag, ...rest } = saved as Record<string, unknown>
  const out: Record<string, unknown> = { ...rest }
  if (typeof additional === 'number') {
    if (out.taxableAdditional == null) out.taxableAdditional = additional
    if (out.additionalBasis == null) out.additionalBasis = 0
  }
  return out as Partial<SimParams>
}

// Mulberry32 — small, fast, deterministic PRNG (used for seedable tests).
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

// Resolve the (stockShift, bondShift) pair for a given params object.
export function resolveScenarioShifts(params: Pick<SimParams, 'scenario' | 'customStockShift' | 'customBondShift'>): ScenarioParams {
  if (params.scenario === 'custom') {
    return { stockShift: params.customStockShift, bondShift: params.customBondShift }
  }
  return SCENARIOS[params.scenario]
}

// Full retirement age (FRA) from birth year, per SSA schedule.
// Born 1960+: 67. Born 1955-1959: 66 + 2 months per year past 1954.
// Born ≤1954: 66. Returns fractional years (e.g. 66.5 for 1957).
export function fraFromBirthYear(birthYear: number): number {
  if (birthYear <= 1954) return 66
  if (birthYear >= 1960) return 67
  return 66 + ((birthYear - 1954) * 2) / 12
}

// SS benefit adjustment factor at claim age. FRA default 67.
//   Early: 5/9 of 1% per month for first 36, 5/12 of 1% per month beyond.
//   Late: 8% per year delayed retirement credit, capped at age 70.
export function ssAdjustment(claimAge: number, fra: number = 67): number {
  if (claimAge === fra) return 1
  if (claimAge < fra) {
    const monthsEarly = (fra - claimAge) * 12
    const first36 = Math.min(monthsEarly, 36)
    const beyond = Math.max(0, monthsEarly - 36)
    const reduction = first36 * (5 / 9) / 100 + beyond * (5 / 12) / 100
    return 1 - reduction
  }
  const yearsLate = Math.min(claimAge - fra, 70 - fra)
  return 1 + 0.08 * yearsLate
}

// 2026 Social Security wage base in real $. Treated as fixed in real terms
// throughout the sim (consistent with how tax brackets are held constant). The
// wage base grows ~1% real/yr historically; treating it flat is slightly
// conservative (overstates SS tax in later nominal years) and keeps the math simple.
export const SS_WAGE_BASE_REAL = 176_100  // $

// SSA earnings-test exempt amounts (2026, real $). Before FRA, benefits are
// reduced $1 for every $2 of wages above the lower threshold. In the year FRA
// is reached, the reduction is $1 per $3 above the higher threshold.
export const SS_EARNINGS_EXEMPT_BEFORE_FRA = 22_320   // $/yr real
export const SS_EARNINGS_EXEMPT_FRA_YEAR   = 59_520   // $/yr real

// Employee-side payroll taxes (SS + Medicare) on a single person's gross W-2 wages.
// For MFJ the additional-Medicare threshold is $250K combined; since the user is
// retired and has no W-2 income, combined household wages equal the spouse's wages.
// Returns total annual employee payroll tax in dollars.
export function computeSpousePayrollTax(annualGrossWages: number, status: FilingStatus): number {
  const ss = 0.062 * Math.min(annualGrossWages, SS_WAGE_BASE_REAL)
  const medicare = 0.0145 * annualGrossWages
  const addlMedicareThreshold = status === 'mfj' ? 250_000 : 200_000
  const addlMedicare = 0.009 * Math.max(0, annualGrossWages - addlMedicareThreshold)
  return ss + medicare + addlMedicare
}

// Reduce monthly SS benefit by the SSA earnings test while spouse is working
// before FRA. Amounts withheld before FRA are credited back as a higher benefit
// after FRA (the SSA does this automatically), but modeling that recapture
// requires tracking cumulative withheld amounts; omitted here as a known
// conservative simplification — it slightly understates lifetime SS income for
// early claimers who work past FRA.
export function spouseSsAfterEarningsTest(
  ssMonthlyM: number,       // $M/month, already claiming
  spouseGrossWorkM: number, // $M/month gross wages
  spouseAge: number,
  spouseFra: number,
): number {
  if (spouseGrossWorkM <= 0 || spouseAge >= spouseFra) return ssMonthlyM
  const annualWages = spouseGrossWorkM * 12 * 1_000_000  // → $
  const annualSs = ssMonthlyM * 12 * 1_000_000           // → $
  let withheld: number
  if (spouseAge < spouseFra) {
    withheld = Math.max(0, annualWages - SS_EARNINGS_EXEMPT_BEFORE_FRA) / 2
  } else {
    withheld = Math.max(0, annualWages - SS_EARNINGS_EXEMPT_FRA_YEAR) / 3
  }
  return Math.max(0, annualSs - withheld) / 12 / 1_000_000  // → $M/month
}

// Linear interpolation quantile on a sorted ascending array.
export function quantile(sorted: ArrayLike<number>, q: number): number {
  const n = sorted.length
  if (n === 0) return 0
  const idx = q * (n - 1)
  const lo = Math.floor(idx)
  const hi = Math.ceil(idx)
  if (lo === hi) return sorted[lo]
  return sorted[lo] * (hi - idx) + sorted[hi] * (idx - lo)
}

export interface SimResult {
  fanYears: number[]
  fanAges: number[]
  fanWealth: Float64Array[]
  finalWealth: Float64Array
  ruined: Uint8Array
  startingEquity: number
  startingCash: number
  startingTotal: number
  years: number
  pctAboveStart: number
  pctRuin: number
  medianFinalM: number
  p10FinalM: number
}

export function simulate(params: SimParams): SimResult {
  const rand = params.seed != null ? mulberry32(params.seed) : Math.random
  const { stockShift, bondShift } = resolveScenarioShifts(params)
  const data = HISTORICAL_RETURNS
  const dataLen = data.length

  // Bucket totals (in $M, real).
  const taxableTotal = Math.max(0, params.epicExit + params.taxableAdditional)
  const tradTotal = Math.max(0, params.traditional)
  const rothTotal = Math.max(0, params.roth)
  // Epic exit always carries full basis (just sold). Pre-existing taxable
  // additional carries user-supplied basis (capped to its value).
  const baselineBasis = Math.max(0, params.epicExit) +
    Math.min(Math.max(0, params.additionalBasis), Math.max(0, params.taxableAdditional))
  const totalPortfolio = taxableTotal + tradTotal + rothTotal

  const stockPct = Math.max(0, params.stockPct)
  const bondPct = Math.max(0, params.bondPct)
  const equityPct = stockPct + bondPct
  const cashPct = Math.max(0, 1 - equityPct)

  // Cash buffer is funded from the taxable bucket.
  const cashTarget0 = totalPortfolio * cashPct
  const startingCash = Math.min(taxableTotal, cashTarget0)
  const taxableEquity0 = taxableTotal - startingCash
  const taxableBasis0 = taxableTotal > 0 ? baselineBasis * (taxableEquity0 / taxableTotal) : 0
  const startingEquity = taxableEquity0 + tradTotal + rothTotal
  const startingTotal = startingEquity + startingCash

  // Within equity, weights for stock vs. bond.
  const wS = equityPct > 0 ? stockPct / equityPct : 0
  const wB = 1 - wS

  const defaultSpendK = params.defaultSpend
  const minSpendK = params.minSpend
  const hiK = params.healthInsurance

  const ssAdj = ssAdjustment(params.claimAge, params.fra)
  const ssAnnual = (params.ssMonthly * 12) * ssAdj  // $/yr real

  const hasSpouse = params.includeSpouse
  const spouseSsAdj = hasSpouse ? ssAdjustment(params.spouseClaimAge, params.fra) : 1
  const spouseSsAnnual = hasSpouse ? (params.spouseSsMonthly * 12) * spouseSsAdj : 0

  const status: FilingStatus = hasSpouse ? 'mfj' : 'single'

  // Spouse work income. Precompute monthly figures (constant salary assumption).
  const spouseAnnualGross = hasSpouse && params.spouseWorkIncome > 0
    ? params.spouseWorkIncome * 1_000  // $K → $
    : 0
  // Annual payroll tax amortized monthly. Computed once — constant real salary assumption.
  const spousePayrollMonthM = spouseAnnualGross > 0
    ? computeSpousePayrollTax(spouseAnnualGross, status) / 12 / 1_000_000
    : 0
  const spouseWorkMonthM = spouseAnnualGross / 12 / 1_000_000  // $M/month gross
  const stateLTCGRate = Math.max(0, params.stateLTCGRate)

  const cashTarget = startingCash
  const Y = Math.max(1, Math.round(params.endAge - params.currentAge))
  const M = Y * 12  // total months in simulation
  const N = Math.max(1, Math.round(params.paths))

  // Fan years: 0, 5, 10, ... up to Y (in years, not months).
  const fanYears: number[] = []
  for (let y = 0; y <= Y; y += 5) fanYears.push(y)
  if (fanYears[fanYears.length - 1] !== Y) fanYears.push(Y)
  const fanAges = fanYears.map(y => params.currentAge + y)

  const yearToFanIdx = new Map<number, number>()
  fanYears.forEach((y, idx) => yearToFanIdx.set(y, idx))

  const fanWealth: Float64Array[] = fanYears.map(() => new Float64Array(N))
  const finalWealth = new Float64Array(N)
  const ruined = new Uint8Array(N)

  const fan0Idx = yearToFanIdx.get(0)
  if (fan0Idx != null) fanWealth[fan0Idx].fill(startingTotal)

  const jumpProb = 1 / MEAN_BLOCK_LEN

  // Initial HI estimate (zero MAGI) — seeds the first year's monthly
  // amortization. IRMAA is updated annually at year-end using the year's
  // actual MAGI, mirroring the real 2-year-lagged IRMAA lookback.
  const spouseEHIAtStart = hasSpouse && params.spouseHasEmployerHI
    && params.spouseCurrentAge <= params.spouseStopWorkAge
  const initialHIM = healthInsuranceCost({
    ownerAge: params.currentAge,
    spouseAge: params.spouseCurrentAge,
    hasSpouse,
    preMedicareCost: spouseEHIAtStart ? 0 : hiK * 1000,
    zeroHIPost65: params.zeroHIPost65,
    magi: 0,
    status,
  }) / 1_000_000

  for (let i = 0; i < N; i++) {
    let cash = startingCash
    let taxableEq = taxableEquity0
    let taxableBasis = taxableBasis0
    let tradEq = tradTotal
    let rothEq = rothTotal
    let isRuined = false
    let dataIdx = Math.floor(rand() * dataLen)

    // Annual income accumulators — reset each simulation year.
    let yearTradWithdrawal = 0
    let yearLTCG = 0
    let yearSSTaxable = 0
    let yearSpouseWorkGross = 0  // $M, spouse gross W-2 — added to ordinary income at year-end
    // Prior-year annual HI in $M — amortized 1/12 per month.
    let pathHIM = initialHIM
    // Taxable equity at the start of each simulation year (for refill check).
    let yearStartTaxableEq = taxableEq

    for (let m = 1; m <= M; m++) {
      const monthOfYear = ((m - 1) % 12) + 1  // 1..12
      const y = Math.ceil(m / 12)              // simulation year 1..Y
      const isYearEnd = monthOfYear === 12 || m === M
      const age = params.currentAge + m / 12
      const spouseAge = params.spouseCurrentAge + m / 12

      // Once a path is ruined it stops accumulating.
      if (isRuined) {
        cash = 0; taxableEq = 0; taxableBasis = 0; tradEq = 0; rothEq = 0
        if (isYearEnd) {
          const fanIdx = yearToFanIdx.get(y)
          if (fanIdx != null) fanWealth[fanIdx][i] = 0
        }
        continue
      }

      // Stationary bootstrap: each month, with probability 1/L jump to a
      // new uniformly-random historical month; otherwise advance one month.
      if (m > 1) {
        if (rand() < jumpProb) dataIdx = Math.floor(rand() * dataLen)
        else dataIdx = (dataIdx + 1) % dataLen
      }
      const sample = data[dataIdx]
      // Scenario shifts are defined as annual return adjustments (e.g. -3.5%/yr
      // for cautious). Divide by 12 to apply correctly to monthly returns.
      const stockR = sample.stockReal + stockShift / 12
      const bondR = sample.bondReal + bondShift / 12
      const portR = wS * stockR + wB * bondR

      // Erode taxable basis by this month's CPI. Cost basis is fixed in
      // nominal $ in real life, but the simulator tracks everything in real
      // $ — so basis loses purchasing power each month. Using the sampled
      // month's actual CPI keeps each path internally consistent.
      if (taxableBasis > 0) {
        taxableBasis = Math.max(0, taxableBasis / (1 + sample.inflation))
      }

      // Apply monthly growth uniformly across all three equity buckets.
      taxableEq = Math.max(0, taxableEq * (1 + portR))
      tradEq = Math.max(0, tradEq * (1 + portR))
      rothEq = Math.max(0, rothEq * (1 + portR))

      // Monthly SS income — each spouse claims at their own age.
      const ownerSsM = age >= params.claimAge ? ssAnnual / 12 / 1_000_000 : 0
      const spouseWorking = hasSpouse
        && spouseAnnualGross > 0
        && spouseAge <= params.spouseStopWorkAge
      // Employer HI is independent of whether income is tracked — it just requires
      // the spouse to still be employed (age ≤ stop-work age).
      const spouseHasEHI = hasSpouse && params.spouseHasEmployerHI
        && spouseAge <= params.spouseStopWorkAge
      const spouseSsRawM = hasSpouse && spouseAge >= params.spouseClaimAge
        ? spouseSsAnnual / 12 / 1_000_000 : 0
      // Apply SSA earnings test: benefits are reduced while claiming before FRA + working.
      const spouseSsM = spouseSsAfterEarningsTest(
        spouseSsRawM, spouseWorking ? spouseWorkMonthM : 0, spouseAge, params.spouseFra)
      const ssGrossM = ownerSsM + spouseSsM
      const ssTaxableMonthM = ssGrossM * 0.85

      // Spouse work income net of payroll tax (income tax settled annually).
      const spouseNetWorkMonthM = spouseWorking
        ? spouseWorkMonthM - spousePayrollMonthM
        : 0

      // Monthly behavioral spending ramp (same formula as annual, scaled 1/12).
      const wealthRatio = startingTotal > 0
        ? (taxableEq + tradEq + rothEq + cash) / startingTotal : 0
      const spendT = Math.max(0, Math.min(1,
        (wealthRatio - SPEND_RAMP_FLOOR) / (1 - SPEND_RAMP_FLOOR)))
      const baseSpendMonthly = (minSpendK + spendT * (defaultSpendK - minSpendK)) / 1000 / 12

      // Monthly HI: amortize prior year's annual HI 1/12 per month.
      const hiMonthly = pathHIM / 12

      // Basis fraction — fixed for this month (post-growth state). Pulls
      // and refills consume basis pro-rata.
      const basisFraction = taxableEq > 0 ? Math.min(1, taxableBasis / taxableEq) : 1

      // Monthly net need from portfolio. SS and spouse's net work income (gross minus
      // payroll taxes; income tax on gross is handled at year-end) reduce the draw.
      let need = baseSpendMonthly + hiMonthly - ssGrossM - spouseNetWorkMonthM
      let pulledCash = 0, pulledTaxable = 0, pulledTrad = 0, pulledRoth = 0
      let shortfall = false

      if (need <= 0) {
        pulledCash = need  // surplus: negative pull = cash deposit
      } else {
        if (cash > 0) { pulledCash = Math.min(cash, need); need -= pulledCash }
        if (need > 0 && taxableEq > 0) {
          pulledTaxable = Math.min(taxableEq, need); need -= pulledTaxable
        }
        if (need > 0 && age >= RETIREMENT_ACCESS_AGE && tradEq > 0) {
          pulledTrad = Math.min(tradEq, need); need -= pulledTrad
        }
        if (need > 0 && age >= RETIREMENT_ACCESS_AGE && rothEq > 0) {
          pulledRoth = Math.min(rothEq, need); need -= pulledRoth
        }
        if (need > 1e-9) shortfall = true
      }

      // Apply pulls.
      cash -= pulledCash
      if (pulledTaxable > 0) {
        const basisReturned = pulledTaxable * basisFraction
        taxableEq -= pulledTaxable
        taxableBasis = Math.max(0, taxableBasis - basisReturned)
        yearLTCG += pulledTaxable * (1 - basisFraction)
      }
      tradEq -= pulledTrad
      rothEq -= pulledRoth
      yearTradWithdrawal += pulledTrad
      yearSSTaxable += ssTaxableMonthM
      if (spouseWorking) yearSpouseWorkGross += spouseWorkMonthM

      if (cash < 0) cash = 0
      if (taxableEq < 0) taxableEq = 0
      if (tradEq < 0) tradEq = 0
      if (rothEq < 0) rothEq = 0

      // Ruin: monthly spending shortfall, or portfolio fully exhausted.
      if (shortfall) isRuined = true
      if (cash + taxableEq + tradEq + rothEq <= 0) isRuined = true

      if (isYearEnd) {
        if (!isRuined) {
          // Update HI for next year using this year's accumulated MAGI.
          // Spouse W-2 income is included — it raises MAGI for IRMAA purposes.
          const yearMAGI = (yearTradWithdrawal + yearSpouseWorkGross + yearSSTaxable + yearLTCG) * 1_000_000
          pathHIM = healthInsuranceCost({
            ownerAge: age,
            spouseAge,
            hasSpouse,
            preMedicareCost: spouseHasEHI ? 0 : hiK * 1000,
            zeroHIPost65: params.zeroHIPost65,
            magi: yearMAGI,
            status,
          }) / 1_000_000

          // Annual tax on the year's accumulated income. Spouse W-2 gross is
          // treated as ordinary income (same bracket path as 401k withdrawals;
          // WI brackets and the federal standard deduction both apply correctly).
          const taxRes = computeAnnualTax({
            traditionalWithdrawal: (yearTradWithdrawal + yearSpouseWorkGross) * 1_000_000,
            ssTaxable: yearSSTaxable * 1_000_000,
            ltcg: yearLTCG * 1_000_000,
            status,
            stateLTCGRate,
          })
          const taxM = taxRes.total / 1_000_000

          // Pay annual tax bill: cash → taxable → trad → roth.
          if (taxM > 0) {
            const bf2 = taxableEq > 0 ? Math.min(1, taxableBasis / taxableEq) : 1
            let taxRemain = taxM
            if (cash > 0) {
              const p = Math.min(cash, taxRemain); cash -= p; taxRemain -= p
            }
            if (taxRemain > 0 && taxableEq > 0) {
              const p = Math.min(taxableEq, taxRemain)
              taxableEq -= p
              taxableBasis = Math.max(0, taxableBasis - p * bf2)
              taxRemain -= p
            }
            if (taxRemain > 0 && tradEq > 0) {
              const p = Math.min(tradEq, taxRemain); tradEq -= p; taxRemain -= p
            }
            if (taxRemain > 0 && rothEq > 0) {
              const p = Math.min(rothEq, taxRemain); rothEq -= p; taxRemain -= p
            }
            if (taxRemain > 1e-9) isRuined = true
          }
        }

        if (!isRuined) {
          // Refill cash buffer from this year's net positive equity gain in
          // the taxable bucket. The refill is a sale: it realizes LTCG on
          // the gain portion. Recompute the year's marginal tax with the
          // extra gain and pay the delta out of cash.
          const equityChangeTaxable = taxableEq - yearStartTaxableEq
          if (equityChangeTaxable > 0 && cash < cashTarget && taxableEq > 0) {
            const refillRoom = cashTarget - cash
            const grossSell = Math.min(refillRoom, equityChangeTaxable)
            if (grossSell > 0) {
              const refillBasisFraction = taxableEq > 0 ? Math.min(1, taxableBasis / taxableEq) : 1
              const refillGainM = grossSell * (1 - refillBasisFraction)
              const basisReturned = grossSell * refillBasisFraction
              const taxBefore = computeAnnualTax({
                traditionalWithdrawal: (yearTradWithdrawal + yearSpouseWorkGross) * 1_000_000,
                ssTaxable: yearSSTaxable * 1_000_000,
                ltcg: yearLTCG * 1_000_000,
                status, stateLTCGRate,
              })
              const taxAfter = computeAnnualTax({
                traditionalWithdrawal: (yearTradWithdrawal + yearSpouseWorkGross) * 1_000_000,
                ssTaxable: yearSSTaxable * 1_000_000,
                ltcg: (yearLTCG + refillGainM) * 1_000_000,
                status, stateLTCGRate,
              })
              const refillTaxM = Math.max(0, (taxAfter.total - taxBefore.total) / 1_000_000)
              taxableEq -= grossSell
              taxableBasis = Math.max(0, taxableBasis - basisReturned)
              cash += grossSell - refillTaxM
              if (cash < 0) cash = 0
            }
          }

          if (cash < 0) cash = 0
          if (taxableEq < 0) taxableEq = 0
          if (tradEq < 0) tradEq = 0
          if (rothEq < 0) rothEq = 0
        }

        const fanIdx = yearToFanIdx.get(y)
        if (fanIdx != null) {
          fanWealth[fanIdx][i] = isRuined ? 0 : (cash + taxableEq + tradEq + rothEq)
        }

        // Reset annual accumulators and advance year-start snapshot.
        yearTradWithdrawal = 0
        yearLTCG = 0
        yearSSTaxable = 0
        yearSpouseWorkGross = 0
        yearStartTaxableEq = taxableEq
      }
    }

    finalWealth[i] = cash + taxableEq + tradEq + rothEq
    ruined[i] = isRuined ? 1 : 0
  }

  const sortedFinal = Float64Array.from(finalWealth)
  sortedFinal.sort()
  const medianFinalM = quantile(sortedFinal, 0.5)
  const p10FinalM = quantile(sortedFinal, 0.10)

  let above = 0
  let ruin = 0
  for (let i = 0; i < N; i++) {
    if (finalWealth[i] > startingTotal) above++
    if (ruined[i]) ruin++
  }

  return {
    fanYears,
    fanAges,
    fanWealth,
    finalWealth,
    ruined,
    startingEquity,
    startingCash,
    startingTotal,
    years: Y,
    pctAboveStart: above / N,
    pctRuin: ruin / N,
    medianFinalM,
    p10FinalM,
  }
}


