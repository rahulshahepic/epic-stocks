"""Host-only collector. Never reads container logs, environments or journal text.

Runs from systemd outside the web container. Its sole output is an atomic,
size/row/time-bounded JSON snapshot mounted read-only into the app.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import tempfile
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path

MAX_BYTES = 262_144
MAX_EVENTS = 96


def command(args):
    try:
        return subprocess.run(args, check=True, capture_output=True, text=True, timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None


def collect(environment, output):
    now = datetime.now(timezone.utc)
    previous = {}
    try:
        with output.open("rb") as stream:
            raw = stream.read(MAX_BYTES + 1)
        if len(raw) <= MAX_BYTES:
            previous = json.loads(raw)
        if not isinstance(previous, dict) or previous.get("environment") != environment:
            previous = {}
    except (OSError, ValueError):
        pass
    events = previous.get("events", [])
    if not isinstance(events, list):
        events = []
    retained = []
    for row in events[-MAX_EVENTS:]:
        try:
            stamp = datetime.fromisoformat(row["timestamp_utc"])
            if row["environment"] == environment and now - timedelta(hours=72) <= stamp <= now:
                # Retain only envelopes generated by this collector, never arbitrary context.
                if row["event_code"] not in _CODES:
                    continue
                retained.append(envelope(row["event_code"], environment, stamp,
                                         row.get("api_build"), row.get("reference")))
        except (ValueError, TypeError, KeyError):
            continue
    events = retained
    raw = command(["/usr/bin/docker", "inspect", "--format",
                   '{{json .State.Status}}|{{json .State.OOMKilled}}|{{json .RestartCount}}|'
                   '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}|'
                   '{{index .Config.Labels "org.opencontainers.image.revision"}}', "epic-stocks-app"])
    build = None
    container = "container_unavailable"
    restarts = None
    if raw:
        try:
            status, oom, count, health, revision = raw.split("|")
            restarts = int(count)
            if not 0 <= restarts < 10**9:
                raise ValueError("Invalid restart count")
            build = revision if re.fullmatch(r"[a-f0-9]{7,40}", revision) else None
            container = ("container_oom" if oom == "true" else "container_stopped" if status != '"running"'
                         else "container_unhealthy" if health != "healthy" else "container_running")
        except (ValueError, TypeError):
            container = "container_unavailable"
    scheduler_raw = command(["/usr/bin/systemctl", "show", "epic-stocks-jobs.service",
                             "--property=Result", "--property=ExecMainStartTimestampMonotonic", "--property=ActiveState"])
    scheduler_fields = dict(line.split("=", 1) for line in (scheduler_raw or "").splitlines() if "=" in line)
    scheduler_result = scheduler_fields.get("Result")
    scheduler_ran = scheduler_fields.get("ExecMainStartTimestampMonotonic", "0") != "0"
    scheduler = ("scheduler_succeeded" if scheduler_ran and scheduler_result == "success" and scheduler_fields.get("ActiveState") == "inactive" else
                 "scheduler_failed" if scheduler_ran and scheduler_result in {"exit-code", "timeout", "signal", "core-dump", "resources", "oom-kill", "start-limit-hit"}
                 else "scheduler_unavailable")
    usage = shutil.disk_usage(output.parent)
    disk = "disk_pressure" if usage.used / usage.total >= .9 else "disk_recovered"
    states = {"container": container, "scheduler": scheduler, "disk": disk}
    old_states = previous.get("states", {})
    if not isinstance(old_states, dict):
        old_states = {}
    for component, code in states.items():
        if old_states.get(component) != code:
            event_code = "scheduler_recovered" if code == "scheduler_succeeded" and old_states.get(component) == "scheduler_failed" else code
            events.append(envelope(event_code, environment, now, build))
    if restarts is not None and type(previous.get("restarts")) is int and restarts > previous["restarts"]:
        events.append(envelope("container_restarted", environment, now, build))
    try:
        gap = (now - datetime.fromisoformat(previous["collected_at_utc"])).total_seconds() > 180
    except (KeyError, ValueError, TypeError):
        gap = bool(previous)
    if gap:
        events.append(envelope("collector_gap", environment, now, build))
    snapshot = {"environment": environment, "collected_at_utc": now.isoformat(),
                "history_started_at_utc": previous.get("history_started_at_utc", now.isoformat()),
                "events": events[-MAX_EVENTS:], "states": states, "restarts": restarts}
    raw = json.dumps(snapshot).encode()
    if len(raw) > MAX_BYTES:
        raise ValueError("Diagnostic snapshot too large")
    fd, temporary = tempfile.mkstemp(dir=output.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(raw)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, 0o644)
        os.replace(temporary, output)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


_CODES = {
    "container_running": ("container", "info"), "container_unhealthy": ("container", "error"),
    "container_stopped": ("container", "error"), "container_restarted": ("container", "warning"),
    "container_oom": ("container", "error"), "container_unavailable": ("container", "warning"),
    "scheduler_failed": ("scheduler", "error"), "scheduler_recovered": ("scheduler", "info"),
    "scheduler_succeeded": ("scheduler", "info"),
    "scheduler_unavailable": ("scheduler", "warning"), "collector_gap": ("host", "warning"),
    "disk_pressure": ("host", "warning"), "disk_recovered": ("host", "info"),
}


def envelope(code, environment, now, build=None, reference=None):
    component, severity = _CODES[code]
    return {"timestamp_utc": now.isoformat(), "environment": environment,
            "api_build": build if isinstance(build, str) and re.fullmatch(r"[a-f0-9]{7,40}", build) else None,
            "component": component, "severity": severity, "event_code": code,
            "reference": reference if isinstance(reference, str) and re.fullmatch(r"[a-f0-9]{32}", reference) else uuid.uuid4().hex}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--environment", choices=("staging", "production"), required=True)
    parser.add_argument("--output", type=Path, default=Path("/var/lib/epic-stocks-diagnostics/host.json"))
    args = parser.parse_args()
    collect(args.environment, args.output)
